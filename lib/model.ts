/** The protocols the board ranks, strongest first, with ranks 1..n. */
export function buildBoard(snapshot: Snapshot, model: ModelConstants = MODEL): BoardRow[] {
  const multiples = categoryMultiples(snapshot, model);
  const index = bySlug(snapshot.protocols);
  const chosen = new Map<string, SnapshotProtocol>();
  // The watchlist is the floor: every slug, even one the snapshot no longer carries (it cannot, but the
  // board's coverage is the gate's row and is never gambled on a missing record).
  for (const slug of snapshot.watchlist) {
    const p = index.get(slug);
    if (p !== undefined) chosen.set(slug, p);
  }
  // The early radar: pre-token protocols below the watchlist floor, by TVL, capped. Never a replacement
  // for a watchlist row: a chosen protocol stays chosen.
  const early = snapshot.protocols
    .filter((p) => !chosen.has(p.slug) && isRankable(p) && p.tvl_usd < snapshot.floor_usd)
    .sort((a, b) => b.tvl_usd - a.tvl_usd || (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0))
    .slice(0, EARLY_ROWS);
  for (const p of early) chosen.set(p.slug, p);

  const scored = [...chosen.values()].map((p) => {
    const v = impliedValue(p, snapshot.as_of, model, multiples);
    return { p, ...v };
  });
  scored.sort((a, b) => b.implied - a.implied || (a.p.slug < b.p.slug ? -1 : a.p.slug > b.p.slug ? 1 : 0));
  return scored.map((s, i) => ({
    rank: i + 1,
    slug: s.p.slug,
    name: s.p.name,
    category: s.p.category,
    chains: s.p.chains,
    tvl_usd: s.p.tvl_usd,
    change_7d: s.p.change_7d,
    mcap_usd: s.p.mcap_usd,
    listed_at: s.p.listed_at,
    gecko_id: s.p.gecko_id,
    symbol: s.p.symbol,
    token_status: 'pre-token',
    age_days: s.age,
    implied_value_usd: s.implied,
    model: {
      category_multiple: round4(s.categoryMultiple),
      growth_pct: s.growthPct,
      growth_multiplier: round4(s.growthMult),
      maturity_multiplier: round4(s.maturityMult),
      chain_multiplier: round4(s.chainMult),
      age_days: s.age,
    },
    farm_steps: farmSteps(s.p, s.age).map(stepText),
  }));
}

const round4 = (n: number): number => Math.round(n * 1e4) / 1e4;

/** A step as one string: its action, then its cost and time, within the gate's 20..600 characters. */
export function stepText(step: FarmStep): string {
  let s = `${step.text} Cost: ${step.cost}. Time: ${step.time}.`;
  if (s.length > 600) s = `${s.slice(0, 596)}...`;
  if (s.length < 20) s = `${s} Hold the position and check the protocol's own page.`;
  return s;
}

/** The first chain a protocol names, or a neutral phrase. */
function chainOf(p: SnapshotProtocol): string {
  return p.chains.length > 0 ? p.chains[0]! : 'its main chain';
}

/** What one transaction costs on a chain, in the words a farmer budgets with. */
export function gasFor(chain: string): string {
  const c = chain.toLowerCase();
  if (c.includes('solana')) return 'about $0.02 of gas';
  if (c.includes('base') || c.includes('arbitrum') || c.includes('optimism') || c.includes('polygon') || c.includes('blast') || c.includes('mode')) return 'about $0.30 of gas';
  if (c.includes('ethereum')) return 'about $6 to $12 of gas';
  if (c.includes('bitcoin') || c.includes('hyperliquid')) return 'about $1 of gas';
  return 'about $2 of gas';
}

/** How much capital one farm position needs, from the protocol's own TVL. */
function capitalFor(p: SnapshotProtocol): number {
  if (p.tvl_usd >= 5_000_000_000) return 250;
  if (p.tvl_usd >= 1_000_000_000) return 150;
  if (p.tvl_usd >= 100_000_000) return 100;
  return 50;
}

/** How long to hold, from the protocol's age: younger protocols get a longer qualifying window. */
function holdDaysFor(age: number | null): number {
  if (age === null) return 30;
  if (age < 180) return 60;
  if (age < 365) return 45;
  return 30;
}

/** The category's one action, in the words a farmer can follow. */
function actionFor(p: SnapshotProtocol, capital: number, chain: string): string {
  const c = (p.category ?? '').toLowerCase();
  const name = p.name;
  if (c.includes('lend') || c.includes('cdp') || c.includes('collateral')) return `Supply $${capital} of USDC to ${name} on ${chain} and keep the position open.`;
  if (c.includes('dex') || c.includes('yield') || c.includes('leveraged farm')) return `Provide $${capital} of liquidity to ${name}'s main pool on ${chain} and keep the position open.`;
  if (c.includes('bridge')) return `Bridge $${capital} of USDC to ${chain} through ${name} and use the bridged funds in its app.`;
  if (c.includes('staking') || c.includes('restak')) return `Stake $${capital} of the chain's staking asset through ${name} and keep the receipt.`;
  if (c.includes('perpetual') || c.includes('derivative')) return `Deposit $${capital} of USDC as margin on ${name} and open one small hedge.`;
  if (c.includes('prediction')) return `Fund $${capital} and place one market position on ${name}.`;
  if (c.includes('curator') || c.includes('allocator') || c.includes('risk')) return `Deposit $${capital} into a ${name} vault on ${chain} and keep the shares.`;
  if (c.includes('stable')) return `Mint or deposit $${capital} of the stable asset through ${name} on ${chain}.`;
  if (c.includes('rwa')) return `Mint $${capital} of the protocol's yield asset on ${chain} and hold it.`;
  if (c.includes('insurance')) return `Buy $${capital} of cover from ${name} on ${chain} and keep the policy.`;
  return `Deposit $${capital} of USDC into ${name} on ${chain} and keep the position open.`;
}

/** The weekly qualifying action, tailored to the category so it is a real second touch, not a repeat. */
function weeklyFor(p: SnapshotProtocol, chain: string): string {
  const c = (p.category ?? '').toLowerCase();
  if (c.includes('lend') || c.includes('cdp') || c.includes('collateral')) return `Borrow $10 against the deposit on ${chain}, repay it the same week, and leave the supply position open.`;
  if (c.includes('dex') || c.includes('yield')) return `Swap $10 through ${p.name}'s main pool on ${chain} and add the proceeds back to the position.`;
  if (c.includes('perpetual') || c.includes('derivative')) return `Close and reopen a $10 hedge on ${p.name} so the account shows fresh trading activity.`;
  if (c.includes('bridge')) return `Bridge $10 back across ${p.name} and use the funds once in the destination app.`;
  if (c.includes('staking') || c.includes('restak')) return `Claim or restake the staking rewards ${p.name} shows, even a small amount, and keep the receipt.`;
  if (c.includes('prediction')) return `Settle one small market position on ${p.name} and open the next one.`;
  if (c.includes('curator') || c.includes('allocator') || c.includes('risk')) return `Check the vault's allocation on ${chain} and rebalance $10 into its newest strategy.`;
  return `Make one real use of ${p.name} on ${chain}: a deposit, a swap, a vote or a claim.`;
}

/**
 * A protocol's farm plan: seven steps, each an action with a cost and a time.
 * The plan is derived from the protocol's own record (category, chains, TVL
 * and age), never from a hand-written list of names. Gas is priced by chain,
 * capital by TVL, the hold by age, and the weekly action by category.
 */
export function farmSteps(p: SnapshotProtocol, age: number | null): FarmStep[] {
  const chain = chainOf(p);
  const capital = capitalFor(p);
  const hold = holdDaysFor(age);
  const gas = gasFor(chain);
  const action = actionFor(p, capital, chain);
  return [
    {
      text: `Use a fresh wallet that holds only the funds you plan to farm, and keep its seed phrase offline.`,
      cost: 'nothing to set up, and never share the seed phrase',
      time: '5 minutes',
    },
    {
      text: action,
      cost: `$${capital} of capital and ${gas} for the transaction`,
      time: '15 minutes to set up',
    },
    {
      text: weeklyFor(p, chain),
      cost: gas + ' a week',
      time: '10 minutes a week',
    },
    {
      text: `Hold the position for at least ${hold} days so the activity is counted in more than one snapshot.`,
      cost: `the $${capital} stays in the position`,
      time: `${hold} days`,
    },
    {
      text: `Once a month, open the protocol's own points or rewards page from its own site and check the position is credited.`,
      cost: 'no fee to check, and never pay to claim',
      time: '10 minutes a month',
    },
    {
      text: `Before you withdraw, claim only from the link the protocol itself publishes, and ignore any token offer sent to the wallet.`,
      cost: 'no fee to check, and never pay to claim',
      time: '10 minutes',
    },
    {
      text: `Write the wallet, the dates and every transaction in a farm log so you can repeat the position or unwind it.`,
      cost: 'nothing but the log',
      time: '5 minutes',
    },
  ];
}

/**
 * One sentence saying why a row ranks where it does, from its own figures:
 * the TVL at its category multiple, the seven-day growth, and the age it
 * has run with no token. The dashboard shows this sentence in the detail
 * view, so a reader never has to take the rank on trust.
 */
export function rankReason(row: BoardRow): string {
  const growth = row.change_7d === null ? 'unreported growth' : `${row.change_7d > 0 ? '+' : ''}${row.change_7d.toFixed(2)}% over seven days`;
  const age = row.age_days === null
    ? 'an unreported listing date, so the model uses 365 days'
    : `${row.age_days >= 365 ? `${(row.age_days / 365).toFixed(1)} years` : `${row.age_days} days`} listed with no token on record`;
  const fall = row.change_7d !== null && row.change_7d < 0
    ? ' Growth is negative, so the model marks it down rather than ignoring the fall.'
    : '';
  return `$${row.tvl_usd.toLocaleString('en-US')} of TVL at a ${row.model.category_multiple} category multiple, ` +
    `${growth}, and ${age}.${fall} It records no token: that is what the snapshot says, never proof it has none.`;
}

/**
 * One line per category on the board: how many rows it holds, the multiple
 * the market gave it, and its best protocol. The program prints these
 * lines when it runs, so a run's pricing can be read at a glance.
 */
export function categorySummary(board: BoardRow[]): { category: string; rows: number; multiple: number; best: string }[] {
  const byCat = new Map<string, BoardRow[]>();
  for (const row of board) {
    const key = row.category ?? 'Other';
    const list = byCat.get(key) ?? [];
    list.push(row);
    byCat.set(key, list);
  }
  return [...byCat.entries()]
    .map(([category, rows]) => ({
      category,
      rows: rows.length,
      multiple: rows[0]!.model.category_multiple,
      best: rows[0]!.name,
    }))
    .sort((a, b) => b.rows - a.rows || (a.category < b.category ? -1 : 1));
}

/** The live-token protocols, by market cap, for the dashboard's Live token view. */
export function liveRows(snapshot: Snapshot): LiveRow[] {
  return snapshot.protocols
    .filter((p) => !isPreToken(p) && p.category !== 'CEX')
    .sort((a, b) => (b.mcap_usd ?? 0) - (a.mcap_usd ?? 0) || b.tvl_usd - a.tvl_usd)
    .slice(0, LIVE_ROWS)
    .map((p) => ({
      slug: p.slug,
      name: p.name,
      category: p.category,
      chains: p.chains,
      tvl_usd: p.tvl_usd,
      mcap_usd: p.mcap_usd,
      change_7d: p.change_7d,
    }));
}

