// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and may add
// pre-token protocols below the watchlist floor: the early rows the radar exists to find. A protocol is
// pre-token when its index entry records no token (no market cap, no CoinGecko id, no symbol); the
// snapshot's live-token protocols are kept apart and shown as the market's own values, never mixed into
// the ranked board.
//
// Implied value follows only from the snapshot's own figures, and the one
// number the model does NOT take from a fixed table is the base multiple:
// it is measured from the snapshot itself. For every category, take the
// live-token protocols in that category, take the median of their
// market-cap / TVL, blend it half-and-half with the global median, and
// clamp it to [0.08, 0.55]. A lending protocol is therefore priced like
// lending protocols actually trade, a DEX like DEXes trade, and a category
// with too few live names to trust falls back toward the global median.
// No protocol name is ever special-cased: the same function scores every row.
//
//   categoryMultiple = clamp(0.5 * globalMedian + 0.5 * categoryMedian, 0.08, 0.55)
//   base             = tvl_usd * categoryMultiple
//   growth           = clamp(change_7d, -50, 150) per cent
//   growthMult       = 1 + (growth / 100) * 0.6
//   maturity         = 0.65 + min(age_days, 1460) / 1460 * 0.35   (age unknown: 365)
//   chainMult        = 1 + min(chains - 1, 5) * 0.015
//   implied          = max(1, round(base * growthMult * maturity * chainMult))
//
// Age is the time since DefiLlama first listed the protocol: the best record
// of how long it has run with no token. Chain breadth is a small bonus only:
// a protocol live on five chains reaches more farmers than one on a single
// chain, but breadth never outruns TVL.

